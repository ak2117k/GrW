"""Stock-move feature parity: the ported pipeline (src/mbm/stock_move) reproduces the RESEARCH output.

The fixture (tests/fixtures/stock_move) was generated by running research/stock-daily build.py,
parse_earnings.py and earnings_feats.py (ER_FALLBACK=0) on 3 stocks x 420 bars + NIFTY/VIX and trimmed NSE/BSE
filings; `expected_panel.csv.gz` holds the research rows (features + targets + er_*) of the last 30 sessions.
"""
from __future__ import annotations

import gzip
import json
from pathlib import Path

import numpy as np
import pandas as pd
import pytest

from src.mbm.stock_move import calendar as C
from src.mbm.stock_move import features as F
from src.mbm.stock_move.panel import NoSession, build_panel, frame_reader
from src.mbm.stock_move.prices import COLS, PriceCache

FX = Path(__file__).parent / "fixtures" / "stock_move"
META = json.loads((FX / "meta.json").read_text())
SYMS = META["syms"]
CUTOFF = pd.Timestamp(META["cutoff"])


def load_prices() -> dict[str, pd.DataFrame]:
    out = {}
    for n in ["NIFTYIDX", "INDIAVIX", *SYMS]:
        out[n] = pd.read_csv(FX / f"prices_{n}.csv.gz", parse_dates=["date"], float_precision="round_trip")
    return out


def load_calendar() -> tuple[pd.DataFrame, pd.DataFrame]:
    with gzip.open(FX / "calendar_raw.json.gz", "rt", encoding="utf-8") as fh:
        cal = json.load(fh)
    R, B = [], []
    for s in SYMS:
        r, b = C.nse_rows(s, cal["nse_res"][s], cal["nse_bm"][s])
        R += r
        B += b
        r, b = C.bse_rows(s, cal["bse_res"][s], cal["bse_bm"][s])
        R += r
        B += b
    return C.frames(R, B)


def sectors() -> dict[str, str]:
    s = pd.read_csv(FX / "sectors.csv")
    return dict(zip(s.symbol, s.industry))


@pytest.fixture(scope="module")
def panel():
    R, B = load_calendar()
    p, st = build_panel(SYMS, frame_reader(load_prices()), R, B, sectors(), CUTOFF)
    return p, st


@pytest.fixture(scope="module")
def expected():
    return pd.read_csv(FX / "expected_panel.csv.gz", parse_dates=["date"])


def test_columns_and_order_match_research(panel):
    p, _ = panel
    assert [c for c in p.columns if c != C.MEET_COL] == META["columns"]


def test_feature_values_match_research(panel, expected):
    p, _ = panel
    got = p[p.date.isin(expected.date.unique())].reset_index(drop=True)
    exp = expected.reset_index(drop=True)
    assert got[["date", "sym"]].equals(exp[["date", "sym"]])
    assert (got["sector"].astype(str) == exp["sector"].astype(str)).all()
    bad = {}
    for c in META["columns"]:
        if c in ("date", "sym", "sector"):
            continue
        a, b = got[c].astype(float).to_numpy(), exp[c].astype(float).to_numpy()
        if (np.isnan(a) != np.isnan(b)).any():
            bad[c] = "nan pattern"
            continue
        ok = ~np.isnan(a)
        if ok.any() and np.max(np.abs(a[ok] - b[ok]) / np.maximum(1.0, np.abs(b[ok]))) > 1e-9:
            bad[c] = float(np.max(np.abs(a[ok] - b[ok])))
    assert not bad, bad
    # the fixture exercises the calendar: some rows know an upcoming meeting and some sit inside 5 sessions
    assert exp["er_known"].sum() > 0 and exp["er_in5"].sum() > 0


def test_serving_one_date_equals_the_full_panel_row(panel):
    """Serving scores one date with only data before it. On the panel's LAST date this must equal the
    research row exactly. On earlier dates the research counted days-to-meeting over the realised session
    calendar while serving (like the research tail) counts business days, so a holiday between the date and
    the meeting shifts the er_days_next family by one; every other feature must still be identical (this is
    the no-look-ahead check: nothing after the date leaks into its features)."""
    p, _ = panel
    R, B = load_calendar()
    reader = frame_reader(load_prices())
    cols = [c for c in META["columns"] if not c.startswith("y_") and c not in ("fwd5", "fwd10")]
    holiday_sensitive = {"er_days_next", "er_in5", "er_in10", "er_exp5", "er_season5"}
    dates = sorted(p.date.unique())
    for d in [dates[-1], dates[-8], dates[-17]]:
        d = pd.Timestamp(d)
        one, st = build_panel(SYMS, reader, R, B, sectors(), d + pd.Timedelta(days=1), keep_dates=[d])
        full = p[p.date == d].reset_index(drop=True)
        use = cols if d == dates[-1] else [c for c in cols if c not in holiday_sensitive]
        pd.testing.assert_frame_equal(one[use].reset_index(drop=True), full[use], check_dtype=False,
                                      rtol=1e-12, atol=1e-12)
        assert set(st["close"]) == set(SYMS)


def test_no_index_bar_is_no_session():
    R, B = load_calendar()
    with pytest.raises(NoSession):
        build_panel(SYMS, frame_reader(load_prices()), R, B, sectors(), CUTOFF,
                    keep_dates=[pd.Timestamp("2026-10-20")])   # a holiday in the fixture


def test_feature_columns_exclude_targets_ids_and_display_fields(panel):
    p, _ = panel
    cols = F.feature_columns(p.columns)
    assert "sector" in cols and "er_days_next" in cols and "er_season5" in cols
    assert not any(c.startswith("y_") for c in cols)
    assert not {"date", "sym", "n_hist", "fwd5", "fwd10", C.MEET_COL} & set(cols)


def test_price_cache_round_trips_exactly(tmp_path):
    src = load_prices()["RELIANCE"]
    cache = PriceCache(tmp_path)
    cache.write("RELIANCE", src)
    back = cache.read("RELIANCE")
    pd.testing.assert_frame_equal(back[COLS], src[COLS].reset_index(drop=True), check_dtype=False, rtol=0, atol=0)
    cache.write("M&M", src)                 # '&' symbols get a safe filename
    assert cache.read("M&M").shape == src.shape
    with pytest.raises(ValueError):
        cache.path("../etc")
